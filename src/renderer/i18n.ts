export function dict(lang: Lang): Dict {
  return lang === 'zh' ? zh : en
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''))
}

